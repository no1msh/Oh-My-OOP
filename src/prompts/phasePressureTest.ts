import { z } from "zod";
import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";

const argsShape = {
  current_design: z.string().optional(),
  new_requirement: z.string().optional(),
};

export function registerPhasePressureTest(server: McpServer): void {
  server.registerPrompt(
    "phase-pressure-test",
    {
      title: "단계 압박 테스트 — 추가 요구사항이 깰 부분 미리 보기",
      description:
        "현 설계 + 추가 요구사항 입력 → *어디가 가장 먼저 변할 것 같은가*를 학생이 자가 진단. 1단계→2단계, 또는 새 요구사항 추가 시 학습 장치.",
      argsSchema: argsShape,
    },
    ({ current_design, new_requirement }) => {
      const design = current_design ?? "(현 설계 미입력 — oop_state_read 등으로 조회 가능)";
      const req = new_requirement ?? "(추가 요구사항 미입력 — 학생에게 가상의 변경 시나리오를 물으세요)";
      return {
        messages: [
          {
            role: "user",
            content: {
              type: "text",
              text: [
                `# 단계 압박 테스트`,
                ``,
                `현 설계가 *추가 요구사항*에 직면했을 때 *어디가 가장 먼저 변할지* 학생이 자가 진단하는 장치입니다.`,
                `*추가 요구사항이 기존 설계를 깨는 경험* 자체가 OOP 학습의 핵심입니다 — 1단계에서 깨지지 않는 설계를 짜는 것이 목표가 아니라, *변경에 어떻게 응답하는가*가 학습 대상.`,
                ``,
                `## 현 설계`,
                `\`\`\``,
                design,
                `\`\`\``,
                ``,
                `## 추가 요구사항`,
                `\`\`\``,
                req,
                `\`\`\``,
                ``,
                `## 진단 질문 (학생이 직접 답하도록, 답을 즉시 주지 마세요)`,
                ``,
                `1. 추가 요구사항이 들어왔을 때 *가장 먼저 변할 클래스*는 무엇입니까?`,
                `2. 그 클래스의 *어떤 책임*이 가장 깨지기 쉬워 보입니까?`,
                `3. 변경이 *기존 클래스 1개*에 국한됩니까, 아니면 *여러 클래스*에 퍼집니까?`,
                `4. 분기 N×M, 값 객체 invariant 충돌, 한 데이터의 두 책임, god-object 진화 — *어떤 패턴*으로 깨질 것 같습니까?`,
                `5. 깨질 부분이 *현재 코드의 어색함*과 일치합니까? (어색함은 변경 신호)`,
                ``,
                `## 깨질 패턴 체크리스트 (학생 답변 후 함께 본다)`,
                ``,
                `- **god-object 진화** — 한 클래스에 *여러 책임이 흡수*되어 있다면 새 요구사항이 그 클래스를 더 키운다.`,
                `- **분기 N×M 폭증** — \`when\`/\`if\` 분기 + boolean 플래그가 누적되어 있다면 새 상태/카테고리 추가가 *모든 분기*를 건드린다.`,
                `- **값 객체 invariant 충돌** — 값 객체 산술이 invariant 를 깰 가능성이 있는데 *같은 타입을 반환*한다면 새 산술이 require 위반.`,
                `- **한 데이터의 두 책임** — 같은 필드가 *표현 + 비교* 등 두 책임에 묶여 있다면 새 요구사항이 한쪽만 바꿔도 다른 쪽이 깨진다.`,
                `- **enum 의 표현 어휘 침투** — 도메인 enum 에 UI 문자열이 박혀 있다면 표기 변경 = 도메인 수정.`,
                `- **외부 비교자/외부 mutation** — 객체가 *데이터만 노출*하고 외부가 처리한다면 새 협력자 추가 = 또 다른 외부 처리.`,
                `- **가상 객체** (Manager/Picker/Calculator) — *행동 없는 명사*가 있다면 새 책임이 그 객체에 모인다.`,
                ``,
                `## 진행 원칙`,
                ``,
                `- 깨질 지점을 *학생이 먼저 마킹*하게 하세요. 도구가 *모두 짚어주면* 학습 가치 ↓.`,
                `- 학생이 *놓친* 지점만 추가로 안내.`,
                `- 변경 자체를 *지금 강요*하지 마세요. *예측*만 합니다.`,
                `- 예측이 *맞는지*는 실제 변경을 시도해 볼 때 확인합니다.`,
                ``,
                `**가르침**: 추가 요구사항이 *기존 설계를 깨는 경험*은 실패가 아니라 학습 장치입니다. 1단계 설계가 2단계에서 깨질 때 *처음부터 다시 구현*하고 싶은 충동은 자연스러운 학습 신호입니다.`,
              ].join("\n"),
            },
          },
        ],
      };
    },
  );
}
